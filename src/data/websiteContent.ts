export interface CustomerActivityPayload {
  actionType: string;
  customerName: string;
  customerEmail: string;
  subject?: string;
  details: string;
  targetFeature?: string;
}

export function generateCustomerReport(payload: CustomerActivityPayload): {
  subject: string;
  body: string;
  mailtoUrl: string;
} {
  const timestamp = new Date().toISOString();
  const subject = `[SkillConnect Customer Action Report] ${payload.actionType} - ${payload.customerName}`;
  const body = `SKILLCONNECT CUSTOMER ACTIVITY REPORT
==================================================
Timestamp: ${timestamp}
Activity Category: ${payload.actionType}
Associated Module: ${payload.targetFeature || 'General Platform Feature'}

CUSTOMER INFORMATION:
- Name: ${payload.customerName}
- Email: ${payload.customerEmail}
${payload.subject ? `- Subject: ${payload.subject}\n` : ''}
CUSTOMER REQUEST / SUBMISSION DETAILS:
${payload.details}

--------------------------------------------------
Notification automatically generated by SkillConnect Official Website.
Directly routed to Founder & Developer Abhishek Singh (${BRAND_CONFIG.founderEmail}).
==================================================`;

  const mailtoUrl = `mailto:${BRAND_CONFIG.founderEmail}?subject=${encodeURIComponent(
    subject
  )}&body=${encodeURIComponent(body)}`;

  return { subject, body, mailtoUrl };
}

